#!/usr/bin/env python3
"""Copy the existing application tables from SQLite into an empty PostgreSQL database."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sqlite3
import sys
from datetime import date, datetime, time, timezone
from pathlib import Path
from zoneinfo import ZoneInfo, ZoneInfoNotFoundError

TABLE_COLUMNS = {
    "users": ("id", "name", "email", "password_hash", "role", "department", "created_at"),
    "events": (
        "id", "title", "description", "location", "event_date", "start_time",
        "end_time", "capacity", "category", "created_at",
    ),
    "registrations": (
        "id", "student_id", "event_id", "registration_date", "registration_status",
    ),
    "attendance": (
        "id", "registration_id", "attendance_status", "marked_by", "marked_at",
    ),
}

POSTGRES_SCHEMA = (
    """
    CREATE TABLE IF NOT EXISTS users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name VARCHAR(255) NOT NULL,
        email VARCHAR(255) NOT NULL UNIQUE,
        password_hash VARCHAR(255) NOT NULL,
        role VARCHAR(255) NOT NULL CHECK (role IN ('ADMIN', 'STUDENT', 'FACULTY')),
        department VARCHAR(255),
        created_at TIMESTAMPTZ NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS events (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title VARCHAR(255) NOT NULL,
        description VARCHAR(4000) NOT NULL,
        location VARCHAR(255) NOT NULL,
        event_date DATE NOT NULL,
        start_time TIME(6) NOT NULL,
        end_time TIME(6) NOT NULL,
        capacity INTEGER NOT NULL,
        category VARCHAR(255) NOT NULL,
        created_at TIMESTAMPTZ NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS registrations (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        student_id BIGINT NOT NULL REFERENCES users(id),
        event_id BIGINT NOT NULL REFERENCES events(id),
        registration_date TIMESTAMPTZ NOT NULL,
        registration_status VARCHAR(255) NOT NULL
            CHECK (registration_status IN ('REGISTERED', 'CANCELLED'))
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS attendance (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        registration_id BIGINT NOT NULL UNIQUE REFERENCES registrations(id),
        attendance_status VARCHAR(255) NOT NULL CHECK (attendance_status IN ('PRESENT', 'ABSENT')),
        marked_by BIGINT NOT NULL REFERENCES users(id),
        marked_at TIMESTAMPTZ NOT NULL
    )
    """,
    """
    CREATE UNIQUE INDEX IF NOT EXISTS idx_unique_active_registration
    ON registrations(student_id, event_id)
    WHERE registration_status = 'REGISTERED'
    """,
)


def parse_timestamp(value: object) -> datetime:
    if isinstance(value, (int, float)):
        return datetime.fromtimestamp(value / 1000, tz=timezone.utc)
    parsed = datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    return parsed.replace(tzinfo=timezone.utc) if parsed.tzinfo is None else parsed


def parse_date(value: object, source_zone: ZoneInfo) -> date:
    if isinstance(value, (int, float)):
        return datetime.fromtimestamp(value / 1000, tz=source_zone).date()
    return date.fromisoformat(str(value)[:10])


def parse_time(value: object, source_zone: ZoneInfo) -> time:
    if isinstance(value, (int, float)):
        return datetime.fromtimestamp(value / 1000, tz=source_zone).time().replace(tzinfo=None)
    return time.fromisoformat(str(value))


def read_source(source: Path) -> tuple[dict[str, list[dict[str, object]]], str]:
    connection = sqlite3.connect(f"{source.resolve().as_uri()}?mode=ro", uri=True)
    connection.row_factory = sqlite3.Row
    try:
        rows = {
            table: [dict(row) for row in connection.execute(
                f"SELECT {', '.join(columns)} FROM {table} ORDER BY id"
            )]
            for table, columns in TABLE_COLUMNS.items()
        }
    finally:
        connection.close()

    payload = json.dumps(rows, sort_keys=True, separators=(",", ":"), default=str).encode()
    return rows, hashlib.sha256(payload).hexdigest()


def validate_references(rows: dict[str, list[dict[str, object]]]) -> None:
    user_ids = {row["id"] for row in rows["users"]}
    event_ids = {row["id"] for row in rows["events"]}
    registration_ids = {row["id"] for row in rows["registrations"]}

    for row in rows["registrations"]:
        if row["student_id"] not in user_ids or row["event_id"] not in event_ids:
            raise ValueError(f"Registration {row['id']} references a missing user or event.")
    for row in rows["attendance"]:
        if row["registration_id"] not in registration_ids or row["marked_by"] not in user_ids:
            raise ValueError(f"Attendance {row['id']} references a missing registration or user.")


def convert_rows(
    rows: dict[str, list[dict[str, object]]], source_zone: ZoneInfo
) -> dict[str, list[tuple[object, ...]]]:
    converted: dict[str, list[tuple[object, ...]]] = {}
    for table, table_rows in rows.items():
        converted[table] = []
        for row in table_rows:
            if table == "users":
                values = (
                    row["id"], row["name"], row["email"], row["password_hash"], row["role"],
                    row["department"], parse_timestamp(row["created_at"]),
                )
            elif table == "events":
                values = (
                    row["id"], row["title"], row["description"], row["location"],
                    parse_date(row["event_date"], source_zone),
                    parse_time(row["start_time"], source_zone),
                    parse_time(row["end_time"], source_zone),
                    row["capacity"], row["category"], parse_timestamp(row["created_at"]),
                )
            elif table == "registrations":
                values = (
                    row["id"], row["student_id"], row["event_id"],
                    parse_timestamp(row["registration_date"]), row["registration_status"],
                )
            else:
                values = (
                    row["id"], row["registration_id"], row["attendance_status"],
                    row["marked_by"], parse_timestamp(row["marked_at"]),
                )
            converted[table].append(values)
    return converted


def print_source_summary(
    source: Path,
    rows: dict[str, list[dict[str, object]]],
    digest: str,
    source_zone: ZoneInfo,
) -> None:
    print(f"SQLite source (read-only): {source.resolve()}")
    print(f"Source timezone for stored LocalDate/LocalTime values: {source_zone.key}")
    for table, table_rows in rows.items():
        print(f"{table}: {len(table_rows)} rows")
    if rows["events"]:
        sample = rows["events"][0]
        print(
            "First event local schedule: "
            f"{parse_date(sample['event_date'], source_zone)} "
            f"{parse_time(sample['start_time'], source_zone)}-"
            f"{parse_time(sample['end_time'], source_zone)}"
        )
    print(f"Source data SHA-256: {digest}")


def postgres_connection_options() -> dict[str, str]:
    url = os.getenv("DATABASE_URL")
    if url:
        return {"conninfo": url}
    required = ("DB_HOST", "DB_NAME", "DB_USERNAME", "DB_PASSWORD")
    missing = [key for key in required if not os.getenv(key)]
    if missing:
        raise ValueError(
            "Set DATABASE_URL or all of " + ", ".join(required) + ". Missing: " + ", ".join(missing)
        )
    return {
        "host": os.environ["DB_HOST"],
        "port": os.getenv("DB_PORT", "5432"),
        "dbname": os.environ["DB_NAME"],
        "user": os.environ["DB_USERNAME"],
        "password": os.environ["DB_PASSWORD"],
        "sslmode": os.getenv("DB_SSL_MODE", "require"),
    }


def import_to_postgres(
    rows: dict[str, list[dict[str, object]]],
    converted: dict[str, list[tuple[object, ...]]],
    digest: str,
) -> None:
    try:
        import psycopg
    except ImportError as exc:
        raise RuntimeError("Install migration dependencies with: pip install -r scripts/requirements-migration.txt") from exc

    insert_statements = {
        table: f"INSERT INTO {table} ({', '.join(columns)}) VALUES ({', '.join(['%s'] * len(columns))})"
        for table, columns in TABLE_COLUMNS.items()
    }

    with psycopg.connect(**postgres_connection_options()) as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                "CREATE TABLE IF NOT EXISTS _sqlite_imports "
                "(source_sha256 CHAR(64) PRIMARY KEY, source_file TEXT NOT NULL, imported_at TIMESTAMPTZ NOT NULL DEFAULT now())"
            )
            cursor.execute("SELECT 1 FROM _sqlite_imports WHERE source_sha256 = %s", (digest,))
            if cursor.fetchone():
                print("This exact SQLite snapshot was already imported; no changes made.")
                return

            existing_counts = {}
            for table in TABLE_COLUMNS:
                cursor.execute("SELECT to_regclass(%s)", (table,))
                if cursor.fetchone()[0] is None:
                    existing_counts[table] = 0
                else:
                    cursor.execute(f"SELECT COUNT(*) FROM {table}")
                    existing_counts[table] = cursor.fetchone()[0]
            populated = [table for table, count in existing_counts.items() if count]
            if populated:
                raise RuntimeError(
                    "Refusing to merge into non-empty PostgreSQL tables: " + ", ".join(populated)
                )

            for statement in POSTGRES_SCHEMA:
                cursor.execute(statement)

            for table in TABLE_COLUMNS:
                cursor.executemany(insert_statements[table], converted[table])

            for table, source_rows in rows.items():
                cursor.execute(f"SELECT COUNT(*) FROM {table}")
                target_count = cursor.fetchone()[0]
                if target_count != len(source_rows):
                    raise RuntimeError(
                        f"Row-count mismatch for {table}: SQLite={len(source_rows)}, PostgreSQL={target_count}"
                    )
                cursor.execute(
                    f"SELECT setval(pg_get_serial_sequence(%s, 'id'), COALESCE(MAX(id), 1), COUNT(*) > 0) FROM {table}",
                    (table,),
                )

            cursor.execute(
                "SELECT COUNT(*) FROM registrations r "
                "LEFT JOIN users u ON u.id = r.student_id "
                "LEFT JOIN events e ON e.id = r.event_id "
                "WHERE u.id IS NULL OR e.id IS NULL"
            )
            if cursor.fetchone()[0]:
                raise RuntimeError("PostgreSQL registration foreign-key validation failed.")
            cursor.execute(
                "SELECT COUNT(*) FROM attendance a "
                "LEFT JOIN registrations r ON r.id = a.registration_id "
                "LEFT JOIN users u ON u.id = a.marked_by "
                "WHERE r.id IS NULL OR u.id IS NULL"
            )
            if cursor.fetchone()[0]:
                raise RuntimeError("PostgreSQL attendance foreign-key validation failed.")

            cursor.execute(
                "INSERT INTO _sqlite_imports (source_sha256, source_file) VALUES (%s, %s)",
                (digest, "database.sqlite"),
            )

    print("Migration committed; PostgreSQL row counts match the SQLite snapshot.")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "database" / "database.sqlite",
        help="SQLite database path (default: repository database/database.sqlite)",
    )
    parser.add_argument(
        "--source-time-zone",
        default=os.getenv("SQLITE_SOURCE_TIME_ZONE", "Asia/Kolkata"),
        help="Timezone used by SQLite for LocalDate/LocalTime values (default: Asia/Kolkata)",
    )
    parser.add_argument("--dry-run", action="store_true", help="Inspect and validate source without connecting to PostgreSQL")
    args = parser.parse_args()

    if not args.source.is_file():
        parser.error(f"SQLite source does not exist: {args.source}")
    try:
        source_zone = ZoneInfo(args.source_time_zone)
        rows, digest = read_source(args.source)
        validate_references(rows)
        convert_rows(rows, source_zone)
        print_source_summary(args.source, rows, digest, source_zone)
        if args.dry_run:
            print("Dry run only; PostgreSQL was not contacted and SQLite was not modified.")
            return 0
        import_to_postgres(rows, convert_rows(rows, source_zone), digest)
        return 0
    except (OSError, sqlite3.Error, ValueError, ZoneInfoNotFoundError, RuntimeError) as exc:
        print(f"Migration stopped: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
